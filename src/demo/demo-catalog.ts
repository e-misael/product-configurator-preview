import { deepFreeze } from '../catalog/deep-freeze';
import type { AssetRef, Catalog, NormalizedBox, Plate, PlateShape, TextLayout } from '../domain';

const OBJECT_BOUNDS: NormalizedBox = { x: 0.1, y: 0.1, width: 0.8, height: 0.8 };
const TEXT: TextLayout = {
  area: { x: 0.2, y: 0.3, width: 0.6, height: 0.4 },
  align: 'center',
};
const SCALLOPED_TEXT: TextLayout = {
  area: { x: 0.25, y: 0.35, width: 0.5, height: 0.3 },
  align: 'center',
};
/** Inside the ceramic of the assembled Quadro image, clear of its wooden frame. */
const QUADRO_TEXT: TextLayout = {
  area: { x: 0.25, y: 0.35, width: 0.5, height: 0.3 },
  align: 'center',
};

interface ModelSpec {
  readonly id: string;
  readonly displayName: string;
  readonly sizeLabel: string;
  readonly shape: PlateShape;
  readonly size: number;
  readonly text: TextLayout;
}

function model(spec: ModelSpec): Plate {
  const image: AssetRef = {
    src: `/catalog/plates/${spec.id}/bege.png`,
    alt: `${spec.displayName} ${spec.sizeLabel} (imagem sintética de demonstração)`,
    widthPx: spec.size,
    heightPx: spec.size,
  };
  return {
    id: spec.id,
    type: 'plate',
    displayName: spec.displayName,
    sizeLabel: spec.sizeLabel,
    ceramicColor: 'Bege',
    shape: spec.shape,
    dimensions: { status: 'pending' },
    image: { image, objectBounds: OBJECT_BOUNDS, text: spec.text },
  };
}

