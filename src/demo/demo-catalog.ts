import { deepFreeze } from '../catalog/deep-freeze';
import type { Catalog, NormalizedBox, PlateImage, TextLayout } from '../domain';

const OBJECT_BOUNDS: NormalizedBox = { x: 0.1, y: 0.1, width: 0.8, height: 0.8 };
const RECTANGULAR_TEXT: TextLayout = {
  area: { x: 0.2, y: 0.3, width: 0.6, height: 0.4 },
  align: 'center',
};
const CIRCULAR_TEXT: TextLayout = {
  area: { x: 0.25, y: 0.35, width: 0.5, height: 0.3 },
  align: 'center',
};

function plateImage(
  plateId: string,
  file: string,
  alt: string,
  size: { widthPx: number; heightPx: number },
  variation: Pick<PlateImage, 'colorCategory' | 'colorId'>,
  text: TextLayout,
): PlateImage {
  return {
    ...variation,
    image: {
      src: `/catalog/plates/${plateId}/${file}`,
      alt: `${alt} (imagem sintética de demonstração)`,
      ...size,
    },
    objectBounds: OBJECT_BOUNDS,
    text,
  };
}

